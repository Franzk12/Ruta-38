-- Ruta 38 Repuestos — tablas base de Supabase (proyecto NUEVO)
-- Crea las tablas que index.html espera. Los nombres de columna están tal
-- cual los usa el código (algunos en camelCase entre comillas).
--
-- Este archivo crea SOLO las tablas. La seguridad (RLS), la auditoría y las
-- funciones de stock están en supabase_migracion.sql, que hay que correr
-- siempre después (es el mismo archivo para una base nueva y para una que
-- ya existe, así no hay dos copias que mantener).
--
-- Cómo usarlo:
--   1. Crear un proyecto nuevo en supabase.com
--   2. Project Settings → API → copiar "Project URL" y la "anon public" key
--   3. Pegar esos dos valores en index.html, en las variables
--      SUPABASE_URL y SUPABASE_KEY (buscarlas con Ctrl+F)
--   4. Correr este archivo completo en el SQL Editor del proyecto
--   5. Correr supabase_migracion.sql completo en el SQL Editor
--   6. Authentication → Users → "Add user": crear el email y la contraseña
--      de cada persona que use el sistema (marcar "Auto Confirm User")
--   7. Authentication → Sign In / Providers → DESACTIVAR
--      "Allow new users to sign up" (ver nota en supabase_migracion.sql)
--   8. Abrir index.html, entrar con ese email/contraseña, y en la
--      consola (F12) pegar cargar_datos.js para precargar categorías y marcas
--
-- ¿La base ya existía? Alcanza con correr supabase_migracion.sql.
-- ════════════════════════════════════════════════════════════════════

-- ── PRODUCTOS ──
create table if not exists public.productos (
  id             bigint generated by default as identity primary key,
  codigo         text,
  nombre         text not null,
  categoria      text,
  marca          text,
  precio         numeric(12,2) not null default 0,
  costo          numeric(12,2) not null default 0,
  stock          integer not null default 0,
  "stockDeposito" integer not null default 0,
  "minStock"     integer not null default 0,
  activos        boolean not null default true,
  created_at     timestamptz not null default now()
);
create index if not exists productos_codigo_idx on public.productos (codigo);
create index if not exists productos_nombre_idx on public.productos (nombre);
create index if not exists productos_activos_idx on public.productos (activos);

-- ── VENTAS ──
create table if not exists public.ventas (
  id         bigint generated by default as identity primary key,
  fecha      timestamptz not null default now(),
  total      numeric(12,2) not null default 0,
  pago       numeric(12,2) not null default 0,
  vuelto     numeric(12,2) not null default 0,
  metodo     text not null default 'efectivo',  -- efectivo | transferencia | debito | credito
  anulada    boolean not null default false,
  uid        text  -- id generado en la caja; evita duplicar ventas al reintentar
);
create index if not exists ventas_fecha_idx on public.ventas (fecha desc);
create unique index if not exists ventas_uid_key on public.ventas (uid);

-- ── ITEMS (detalle de cada venta) ──
create table if not exists public.items (
  id           bigint generated by default as identity primary key,
  venta_id     bigint not null references public.ventas (id) on delete cascade,
  producto_id  bigint references public.productos (id) on delete set null,
  cantidad     integer not null,
  precio       numeric(12,2) not null,
  subtotal     numeric(12,2) not null
);
create index if not exists items_venta_id_idx on public.items (venta_id);

-- ── CATEGORÍAS ──
create table if not exists public.categorias (
  id      bigint generated by default as identity primary key,
  nombre  text not null unique,
  activa  boolean not null default true
);

-- ── MARCAS ──
-- OJO: "nombre" acá no es solo el nombre de la marca — cargar_datos.js
-- guarda "Toyota|Corolla,Camry,Hilux,..." (marca + modelos separados por
-- coma) en el mismo campo. No se puede poner UNIQUE porque el código
-- también permite crear marcas sueltas sin modelos desde el tab Admin
-- (agregarMarca solo manda el nombre). Es una mezcla rara pero es la que
-- espera el front-end tal cual está hoy.
create table if not exists public.marcas (
  id      bigint generated by default as identity primary key,
  nombre  text not null,
  activa  boolean not null default true
);
