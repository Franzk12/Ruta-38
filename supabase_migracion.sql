-- AUDITORÍA DE STOCK (trigger)
-- ════════════════════════════════════════════════════════════════════
-- Email del usuario de la sesión (viene en el token de Supabase Auth).
create or replace function public.usuario_email()
returns text language sql stable set search_path = public as $$
  select nullif(auth.jwt() ->> 'email', '');
$$;

-- Anota cada cambio de stock. Las funciones de más abajo avisan el motivo con
-- rpos.origen / rpos.venta_id; si nadie avisó, fue una edición a mano del producto.
-- "security definer": escribe en movimientos_stock aunque el usuario solo pueda leerla.
create or replace function public.registrar_movimiento_stock()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_neg integer;
  v_dep integer;
begin
  if tg_op = 'INSERT' then
    v_neg := new.stock;
    v_dep := new."stockDeposito";
  else
    v_neg := new.stock - old.stock;
    v_dep := new."stockDeposito" - old."stockDeposito";
  end if;
  if v_neg = 0 and v_dep = 0 then
    return new;
  end if;
  insert into public.movimientos_stock
    (producto_id, origen, venta_id, delta_negocio, delta_deposito, stock_negocio, stock_deposito, usuario_id, usuario_email)
  values (
    new.id,
    coalesce(nullif(current_setting('rpos.origen', true), ''), case when tg_op = 'INSERT' then 'alta' else 'edicion' end),
    nullif(current_setting('rpos.venta_id', true), '')::bigint,
    v_neg, v_dep, new.stock, new."stockDeposito",
    auth.uid(), public.usuario_email()
  );
  return new;
end;
$$;

drop trigger if exists productos_movimiento_stock on public.productos;
create trigger productos_movimiento_stock
  after insert or update of stock, "stockDeposito" on public.productos
  for each row execute function public.registrar_movimiento_stock();

-- ════════════════════════════════════════════════════════════════════
-- FUNCIONES DE VENTAS Y STOCK
-- ════════════════════════════════════════════════════════════════════
-- El stock se suma/resta EN LA BASE (stock = stock - cantidad), nunca se
-- escribe un número calculado en el navegador. Así dos cajas que venden el
-- mismo producto al mismo tiempo no se pisan: Postgres las pone en fila.
--
-- registrar_venta y anular_venta son "security definer": son la única forma
-- de escribir en ventas/items (las tablas son de solo lectura para la API).
-- mover_stock y ajustar_stock son "security invoker": corren con los
-- permisos (y RLS) de quien las llama.

-- Stock actual de los productos de una venta — lo usa la app para refrescar su caché.
create or replace function public.stocks_de_venta(p_venta_id bigint)
returns jsonb language sql stable security invoker set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'stock', p.stock)), '[]'::jsonb)
  from public.productos p
  where p.id in (select producto_id from public.items where venta_id = p_venta_id);
$$;

-- Anula una venta y devuelve su stock. Si ya estaba anulada no hace nada
-- (se puede llamar dos veces sin devolver el stock dos veces).
create or replace function public.anular_venta(p_venta_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_anulada boolean;
begin
  select anulada into v_anulada from public.ventas where id = p_venta_id for update;
  if not found then
    raise exception 'La venta % no existe', p_venta_id;
  end if;
  if not v_anulada then
    update public.ventas
       set anulada = true, anulada_por = auth.uid(), anulada_por_email = public.usuario_email(), anulada_en = now()
     where id = p_venta_id;
    perform set_config('rpos.origen', 'anulacion', true);
    perform set_config('rpos.venta_id', p_venta_id::text, true);
    update public.productos p set stock = p.stock + x.cant
    from (select producto_id, sum(cantidad) as cant from public.items
          where venta_id = p_venta_id and producto_id is not null group by producto_id) x
    where p.id = x.producto_id;
    perform set_config('rpos.origen', '', true);
    perform set_config('rpos.venta_id', '', true);
  end if;
  return jsonb_build_object('venta_id', p_venta_id, 'stocks', public.stocks_de_venta(p_venta_id));
end;
$$;

-- Registra venta + items + descuento de stock en una sola transacción.
-- p_venta: {uid, fecha, pago, metodo, anulada}   (total y vuelto se ignoran: los calcula la base)
-- p_items: [{producto_id, cantidad, precio}, ...]
-- · El total es la suma de cantidad × precio de los items que llegan (el precio
--   es el de ESTA venta: en la caja se puede cambiar el precio de un item).
-- · "uid" lo genera la caja: si la misma venta llega dos veces (reintento de la
--   cola offline, respuesta perdida) se devuelve la ya guardada, sin duplicar.
-- · Si llega con anulada=true (se anuló mientras esperaba en la cola) no descuenta stock.
create or replace function public.registrar_venta(p_venta jsonb, p_items jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid     text    := nullif(p_venta->>'uid', '');
  v_anulada boolean := coalesce((p_venta->>'anulada')::boolean, false);
  v_pago    numeric;
  v_total   numeric;
  v_id      bigint;
begin
  -- ¿Ya estaba registrada? No se vuelve a insertar ni a descontar.
  if v_uid is not null then
    select id into v_id from public.ventas where uid = v_uid;
    if v_id is not null then
      if v_anulada then
        return public.anular_venta(v_id);
      end if;
      return jsonb_build_object('venta_id', v_id, 'stocks', public.stocks_de_venta(v_id));
    end if;
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La venta no tiene items';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_items) as i
    where (i->>'cantidad') is null or (i->>'precio') is null
       or (i->>'cantidad')::integer <= 0 or (i->>'precio')::numeric < 0
  ) then
    raise exception 'La venta tiene un item con cantidad o precio inválido';
  end if;

  select coalesce(sum(round((i->>'cantidad')::integer * round((i->>'precio')::numeric, 2), 2)), 0)
    into v_total
    from jsonb_array_elements(p_items) as i;
  v_pago := coalesce((p_venta->>'pago')::numeric, v_total);

  insert into public.ventas (uid, fecha, total, pago, vuelto, metodo, anulada,
                             usuario_id, usuario_email, anulada_por, anulada_por_email, anulada_en)
  values (
    v_uid,
    coalesce((p_venta->>'fecha')::timestamptz, now()),
    v_total,
    v_pago,
    v_pago - v_total,
    coalesce(nullif(p_venta->>'metodo', ''), 'efectivo'),
    v_anulada,
    auth.uid(), public.usuario_email(),
    case when v_anulada then auth.uid() end,
    case when v_anulada then public.usuario_email() end,
    case when v_anulada then now() end
  )
  on conflict (uid) do nothing
  returning id into v_id;

  if v_id is null then
    -- Otra caja/pestaña registró este mismo uid justo en este instante.
    select id into v_id from public.ventas where uid = v_uid;
    if v_anulada then
      return public.anular_venta(v_id);
    end if;
    return jsonb_build_object('venta_id', v_id, 'stocks', public.stocks_de_venta(v_id));
  end if;

  insert into public.items (venta_id, producto_id, cantidad, precio, subtotal)
  select v_id,
         (select p.id from public.productos p where p.id = nullif(i->>'producto_id', '')::bigint),
         (i->>'cantidad')::integer,
         round((i->>'precio')::numeric, 2),
         round((i->>'cantidad')::integer * round((i->>'precio')::numeric, 2), 2)
  from jsonb_array_elements(p_items) as i;

  if not v_anulada then
    perform set_config('rpos.origen', 'venta', true);
    perform set_config('rpos.venta_id', v_id::text, true);
    update public.productos p set stock = p.stock - x.cant
    from (select producto_id, sum(cantidad) as cant from public.items
          where venta_id = v_id and producto_id is not null group by producto_id) x
    where p.id = x.producto_id;
    perform set_config('rpos.origen', '', true);
    perform set_config('rpos.venta_id', '', true);
  end if;

  return jsonb_build_object('venta_id', v_id, 'stocks', public.stocks_de_venta(v_id));
end;
$$;

-- Pasa unidades del depósito al negocio. Falla si en el depósito no alcanza.
create or replace function public.mover_stock(p_id bigint, p_cant integer)
returns jsonb language plpgsql security invoker set search_path = public as $$
declare
  r jsonb;
begin
  perform set_config('rpos.origen', 'mover', true);
  update public.productos
     set stock = stock + p_cant, "stockDeposito" = "stockDeposito" - p_cant
   where id = p_id and p_cant > 0 and "stockDeposito" >= p_cant
  returning jsonb_build_object('id', id, 'stock', stock, 'stockDeposito', "stockDeposito") into r;
  perform set_config('rpos.origen', '', true);
  if r is null then
    raise exception 'No hay suficiente stock en depósito';
  end if;
  return r;
end;
$$;

-- Suma (o resta, con números negativos) stock en lote: carga rápida con escáner,
-- importación de mercadería y "deshacer". Suma sobre el valor de la base, así no
-- pisa ventas hechas mientras tanto. p_items: [{id, negocio, deposito}, ...]
create or replace function public.ajustar_stock(p_items jsonb)
returns jsonb language plpgsql security invoker set search_path = public as $$
declare
  r jsonb;
begin
  perform set_config('rpos.origen', 'ajuste', true);
  with x as (
    select (e->>'id')::bigint as id,
           sum(coalesce((e->>'negocio')::integer, 0))  as neg,
           sum(coalesce((e->>'deposito')::integer, 0)) as dep
    from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) as e
    group by 1
  ), u as (
    update public.productos p
       set stock = p.stock + x.neg, "stockDeposito" = p."stockDeposito" + x.dep
      from x
     where p.id = x.id
    returning p.id, p.stock, p."stockDeposito"
  )
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'stock', stock, 'stockDeposito', "stockDeposito")), '[]'::jsonb)
    into r from u;
  perform set_config('rpos.origen', '', true);
  return r;
end;
$$;

