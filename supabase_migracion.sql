-- ── MOVIMIENTOS DE STOCK (auditoría) ──
-- Una fila por cada cambio de stock de un producto: venta, anulación, carga,
-- movimiento depósito → negocio o edición a mano. La llena un trigger, así
-- queda anotado sin importar desde dónde se hizo el cambio.
create table if not exists public.movimientos_stock (
  id             bigint generated by default as identity primary key,
  fecha          timestamptz not null default now(),
  producto_id    bigint references public.productos (id) on delete set null,
  origen         text not null,  -- venta | anulacion | mover | ajuste | edicion | alta
  venta_id       bigint references public.ventas (id) on delete set null,
  delta_negocio  integer not null default 0,
  delta_deposito integer not null default 0,
  stock_negocio  integer not null,  -- stock que quedó después del cambio
  stock_deposito integer not null,
  usuario_id     uuid,
  usuario_email  text
);
create index if not exists movimientos_stock_producto_idx on public.movimientos_stock (producto_id, fecha desc);
create index if not exists movimientos_stock_fecha_idx    on public.movimientos_stock (fecha desc);

-- ── VALIDACIONES ──
-- "not valid": se exigen para todo lo nuevo sin revisar (ni trabar) filas viejas.
-- A propósito NO se exige stock >= 0: una venta hecha sin conexión ya ocurrió
-- en el mostrador y hay que poder registrarla aunque deje el stock en negativo.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'items_cantidad_positiva') then
    alter table public.items add constraint items_cantidad_positiva check (cantidad > 0) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'items_precio_no_negativo') then
    alter table public.items add constraint items_precio_no_negativo check (precio >= 0) not valid;
  end if;
end $$;

